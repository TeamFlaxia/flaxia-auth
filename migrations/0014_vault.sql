-- Personal Vault storage. Auth is the single authority for the account
-- credential and the encrypted Vault envelope, so a password change can update
-- both atomically. Every byte in these tables is opaque: the server never
-- receives a password, KEK, REK, VK, recovery phrase or item key.
--
--   password ──PBKDF2──► KEK ─┐
--   recovery phrase ──PBKDF2──► REK ─┤─wrap─► VK ─wrap─► item_key ─AES-GCM─► payload
--   device key (IndexedDB) ──────────┘

CREATE TABLE vault_keys (
  user_id       TEXT PRIMARY KEY NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  salt          TEXT NOT NULL,
  recovery_salt TEXT NOT NULL,
  kdf_params    TEXT NOT NULL, -- JSON: {"alg":"PBKDF2-SHA256","iterations":600000}
  wrapped_vk    TEXT NOT NULL, -- base64(iv).base64(ct), KEK-wrapped VK
  recovery_blob TEXT NOT NULL, -- base64(iv).base64(ct), REK-wrapped VK
  vk_version    INTEGER NOT NULL DEFAULT 1,
  created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);

-- A row starts as a pending QR pairing carrying only the joiner's *public*
-- ephemeral X25519 key. It becomes active when an existing device approves it
-- with VK wrapped under a secret only those two devices can derive.
CREATE TABLE device_keys (
  id            TEXT PRIMARY KEY NOT NULL,
  user_id       TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label         TEXT NOT NULL,
  state         TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'active')),
  peer_pub      TEXT NOT NULL DEFAULT '',
  approved_pub  TEXT NOT NULL DEFAULT '',
  wrapped_vk    TEXT NOT NULL DEFAULT '',
  created_at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  expires_at    TEXT NOT NULL DEFAULT '',
  last_seen_at  TEXT
);

CREATE INDEX idx_device_keys_user_id ON device_keys(user_id);
CREATE INDEX idx_device_keys_user_state ON device_keys(user_id, state);

-- id is generated by the client and is also the AAD of both crypto layers, so
-- a payload cannot be moved to another row without failing authentication.
CREATE TABLE vault_items (
  id                TEXT NOT NULL,
  user_id           TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  item_key_wrapped  TEXT NOT NULL,
  payload           TEXT NOT NULL,
  kind              TEXT NOT NULL,
  vk_version        INTEGER NOT NULL DEFAULT 1,
  created_at        TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at        TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  PRIMARY KEY (user_id, id)
);

CREATE INDEX idx_vault_items_user_kind ON vault_items(user_id, kind);

-- The encrypted Vault rewrap travels with a prepared credential change so the
-- verifier and envelope commit in one D1 transaction. NULL means the account
-- has no vault (or is still using the transitional Flaxia-owned store).
